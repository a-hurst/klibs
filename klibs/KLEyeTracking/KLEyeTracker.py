class EventParser():
    """A base class defining how to parse eye events from a given backend.

    This class serves as an adapter between the hardware-specific events generated
    by a given eye tracker and the platform-agnostic eye events generated by klibs.

    """
    def get_type(self, e):
        """Retrieves the type of a given event (e.g. ``BLINK_START``).
        
        Returns:
            int: The type code for the event.

        """
        raise NotImplementedError()

    def eye(self, e):
        """Retrieves the eye for a given event.

        Returns:
            int: ``LEFT_EYE``, ``RIGHT_EYE``, or ``BINOCULAR``.

        """
        raise NotImplementedError()

    def timestamp(self, e):
        """Gets the timestamp for a gaze sample.

        Returns:
            float: The timestamp (in msec) for the gaze sample.

        """
        raise NotImplementedError()

    def left_gaze(self, e):
        """Gets the left eye (x, y) gaze coordinates for a gaze sample.

        Returns:
            tuple or None: The (x, y) gaze coodinates (in pixels) of the left eye for
            the current sample (or None if the left eye is missing or not tracked).
        
        """
        raise NotImplementedError()

    def right_gaze(self, e):
        """Gets the right eye (x, y) gaze coordinates for a gaze sample.

        Returns:
            tuple or None: The (x, y) gaze coodinates (in pixels) of the right eye for
            the current sample (or None if the right eye is missing or not tracked).

        """
        raise NotImplementedError()

    def left_pupil_size(self, e):
        """Gets the left eye pupil size for a gaze sample.

        Pupil size units should be considered arbitrary and tracker-specific.

        Returns:
            float or None: The pupil size (in arbitrary units) of the left eye for
            the current sample (or None if the left eye is missing or not tracked).

        """
        raise NotImplementedError()

    def right_pupil_size(self, e):
        """Gets the right eye pupil size for a gaze sample.

        Pupil size units should be considered arbitrary and tracker-specific.

        Returns:
            float or None: The pupil size (in arbitrary units) of the right eye for
            the current sample (or None if the right eye is missing or not tracked).

        """
        raise NotImplementedError()

    def start_time(self, e):
        """Gets the timestamp (in msec) for the start of the event.

        Returns:
            float: The timestamp (in msec) of the event onset.

        """
        raise NotImplementedError()

    def end_time(self, e):
        """Gets the timestamp (in msec) for the end of the event.

        Returns:
            float: The timestamp (in msec) of the end of the event.

        """
        raise NotImplementedError()

    def start_gaze(self, e):
        """Gets the (x, y) gaze coordinates at the start of the event.

        Returns:
            tuple: The (x, y) gaze coordinates (in pixels) at the start of the event.

        """
        raise NotImplementedError()

    def end_gaze(self, e):
        """Gets the (x, y) gaze coordinates at the end of the event.

        Returns:
            tuple: The (x, y) gaze coordinates (in pixels) at the end of the event.

        """
        raise NotImplementedError()

    def avg_gaze(self, e):
        """Gets the average (x, y) gaze coordinates for the event.

        Returns:
            tuple: The (x, y) gaze coordinates (in pixels) of the average gaze during
            the event.

        """
        raise NotImplementedError()

    def duration(self, e):
        """Gets the total duration (in msec) for the event.

        Returns:
            float: The total duration (in msec) of the event.

        """
        raise NotImplementedError()


